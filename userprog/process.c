/* Starts the first userland program, called "initd", loaded from FILE_NAME.
 * The new thread may be scheduled (and may even exit)
 * before process_create_initd() returns. Returns the initd's
 * thread id, or TID_ERROR if the thread cannot be created.
 * Notice that THIS SHOULD BE CALLED ONCE. */
tid_t
process_create_initd (const char *file_name) {
	char *fn_copy;
	tid_t tid;
	struct wait_status *ws;

	/* Make a copy of FILE_NAME.
	 * Otherwise there's a race between the caller and load(). */
	fn_copy = palloc_get_page (0);
	if (fn_copy == NULL)
		return TID_ERROR;
	strlcpy (fn_copy, file_name, PGSIZE);

	ws = wait_status_create();
	struct initd_args *args;
    if(ws == NULL){
        palloc_free_page(fn_copy);
        return TID_ERROR;
    }
	args = malloc(sizeof *args);
    if(args == NULL){
        free(ws);
        palloc_free_page(fn_copy);
        return TID_ERROR;
    }

	args->file_name = fn_copy;
    args->wait_status = ws;

	/* Create a new thread to execute FILE_NAME. */
	char thread_name[16];
	strlcpy(thread_name, file_name, sizeof thread_name);
	char *name_end = strchr(thread_name, ' ');
	if(name_end != NULL) *name_end = '\0';

	tid = thread_create (thread_name, PRI_DEFAULT, initd, args);
	if (tid == TID_ERROR){
		free(args);
		free(ws);
		palloc_free_page (fn_copy);
		return TID_ERROR;
	}

	ws->tid = tid;
    list_push_back(&thread_current()->children, &ws->elem);

	return tid;
}

/* A thread function that launches first user process. */
static void
initd (void *aux) {
	struct initd_args *args = aux;
    char *f_name = args->file_name;
    struct thread *cur = thread_current();
    cur->wait_status = args->wait_status;
    cur->is_user_process = true;
    free(args);

#ifdef VM
	supplemental_page_table_init (&thread_current ()->spt);
#endif

	process_init ();

	if (process_exec (f_name) < 0)
		PANIC("Fail to launch initd\n");
	NOT_REACHED ();
}

/* Clones the current process as `name`. Returns the new process's thread id, or
 * TID_ERROR if the thread cannot be created. */
tid_t
process_fork (const char *name, struct intr_frame *if_) {
	struct wait_status *ws = wait_status_create();
	if(ws == NULL) return TID_ERROR;

	struct fork_args args;
	args.parent = thread_current();
	args.if_ = *if_;
	args.wait_status = ws;
	args.success = false;
	sema_init (&args.fork_sema, 0);

	tid_t tid = thread_create(name, PRI_DEFAULT, __do_fork, &args);

	if(tid == TID_ERROR){
		free (ws);
		return TID_ERROR;
	}

	ws->tid = tid;
	list_push_back(&thread_current()->children, &ws->elem);

	/* 자식이 args를 다 쓰고 복제를 완료할 때까지 기다린다. */
	sema_down(&args.fork_sema);

	if(!args.success){
		list_remove(&ws->elem);
		wait_status_release(ws);
		return TID_ERROR;
	}

	return tid;
}

